import { use, useEffect, useState } from "react";
import Link from "next/link";
import { format, parseISO } from "date-fns";
import {
  Briefcase,
  Check,
  ExternalLink,
  FileText,
  Pencil,
  Send,
  X,
} from "lucide-react";
