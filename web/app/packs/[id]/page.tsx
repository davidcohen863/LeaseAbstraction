// ---- Markdown renderer (Word-styled) -----------------------------------

function Markdown({ text }: { text: string }) {
  const blocks = parseBlocks(text);
  return (
    <div style={{ lineHeight: 1.55, fontSize: "11pt" }}>
      {blocks.map((b, i) => {
        if (b.type === "heading") {
          if (b.level === 1) {
            return (
              <h1 key={i} style={{ fontSize: "20pt", fontWeight: 600, marginTop: i === 0 ? 0 : "1.4em", marginBottom: "0.6em", lineHeight: 1.25 }}>
                {renderInline(b.text)}
              </h1>
            );
          }
          if (b.level === 2) {
            return (
              <h2 key={i} style={{ fontSize: "14pt", fontWeight: 600, marginTop: "1.4em", marginBottom: "0.5em", lineHeight: 1.3, color: "#0f172a" }}>
                {renderInline(b.text)}
              </h2>
            );
          }
          return (
            <h3 key={i} style={{ fontSize: "12pt", fontWeight: 600, marginTop: "1.1em", marginBottom: "0.4em", lineHeight: 1.3, color: "#0f172a" }}>
              {renderInline(b.text)}
            </h3>
          );
        }
        if (b.type === "bullets") {
          return (
            <ul key={i} style={{ marginLeft: "1.4em", marginTop: "0.4em", marginBottom: "0.6em", listStyleType: "disc" }}>
              {b.items.map((item, j) => (
                <li key={j} style={{ marginBottom: "0.25em" }}>{renderInline(item)}</li>
              ))}
            </ul>
          );
        }
        if (b.type === "numbered") {
          return (
            <ol key={i} style={{ marginLeft: "1.4em", marginTop: "0.4em", marginBottom: "0.6em", listStyleType: "decimal" }}>
              {b.items.map((item, j) => (
                <li key={j} style={{ marginBottom: "0.25em" }}>{renderInline(item)}</li>
              ))}
            </ol>
          );
        }
        if (b.type === "table") {
          return (
            <table key={i} style={{ width: "100%", borderCollapse: "collapse", marginTop: "0.6em", marginBottom: "0.6em", fontSize: "10pt" }}>
              <thead>
                <tr>
                  {b.header.map((h, j) => (
                    <th key={j} style={{ borderBottom: "2px solid #1e293b", padding: "6px 8px", textAlign: "left", fontWeight: 600 }}>
                      {renderInline(h)}
                    </th>
                  ))}
                </tr>
              </thead>
              <tbody>
                {b.rows.map((row, ri) => (
                  <tr key={ri}>
                    {row.map((c, ci) => (
                      <td key={ci} style={{ borderBottom: "1px solid #e2e8f0", padding: "6px 8px", verticalAlign: "top" }}>
                        {renderInline(c)}
                      </td>
                    ))}
                  </tr>
                ))}
              </tbody>
            </table>
          );
        }
        if (b.type === "rule") {
          return <hr key={i} style={{ border: 0, borderTop: "1px solid #e2e8f0", margin: "1.2em 0" }} />;
        }
        return (
          <p key={i} style={{ margin: "0.5em 0", textAlign: "justify" }}>
            {renderInline(b.text)}
          </p>
        );
      })}
    </div>
  );
}

type Block =
  | { type: "heading"; level: 1 | 2 | 3; text: string }
  | { type: "paragraph"; text: string }
  | { type: "bullets"; items: string[] }
  | { type: "numbered"; items: string[] }
  | { type: "table"; header: string[]; rows: string[][] }
  | { type: "rule" };

function parseBlocks(md: string): Block[] {
  const lines = md.replace(/\r\n/g, "\n").split("\n");
  const blocks: Block[] = [];
  let i = 0;
  while (i < lines.length) {
    const line = lines[i];
    if (!line.trim()) { i++; continue; }

    if (/^---+$/.test(line.trim())) { blocks.push({ type: "rule" }); i++; continue; }

    if (line.startsWith("### ")) { blocks.push({ type: "heading", level: 3, text: line.slice(4) }); i++; continue; }
    if (line.startsWith("## "))  { blocks.push({ type: "heading", level: 2, text: line.slice(3) }); i++; continue; }
    if (line.startsWith("# "))   { blocks.push({ type: "heading", level: 1, text: line.slice(2) }); i++; continue; }

    if (line.trimStart().startsWith("|") && i + 1 < lines.length && lines[i + 1].includes("---")) {
      const tableLines: string[] = [];
      while (i < lines.length && lines[i].trimStart().startsWith("|")) { tableLines.push(lines[i]); i++; }
      const cells = (l: string) => l.trim().replace(/^\||\|$/g, "").split("|").map((c) => c.trim());
      const header = cells(tableLines[0]);
      const rows = tableLines.slice(2).map(cells);
      blocks.push({ type: "table", header, rows });
      continue;
    }

    if (/^[-*] /.test(line.trimStart())) {
      const items: string[] = [];
      while (i < lines.length && /^[-*] /.test(lines[i].trimStart())) {
        items.push(lines[i].trimStart().replace(/^[-*] /, ""));
        i++;
      }
      blocks.push({ type: "bullets", items });
      continue;
    }

    if (/^\d+\.\s/.test(line.trimStart())) {
      const items: string[] = [];
      while (i < lines.length && /^\d+\.\s/.test(lines[i].trimStart())) {
        items.push(lines[i].trimStart().replace(/^\d+\.\s/, ""));
        i++;
      }
      blocks.push({ type: "numbered", items });
      continue;
    }

    const paraLines = [line];
    i++;
    while (i < lines.length && lines[i].trim() && !/^([#\-*|]|\d+\.\s|---+$)/.test(lines[i].trimStart())) {
      paraLines.push(lines[i]);
      i++;
    }
    blocks.push({ type: "paragraph", text: paraLines.join(" ") });
  }
  return blocks;
}

function renderInline(text: string): React.ReactNode {
  const parts = text.split(/(\*\*[^*]+\*\*)/g);
  return (
    <>
      {parts.map((p, i) =>
        p.startsWith("**") && p.endsWith("**")
          ? <strong key={i}>{p.slice(2, -2)}</strong>
          : <span key={i}>{p}</span>
      )}
    </>
  );
}

// ---- Comparables drawer -------------------------------------------------

function ComparablesDrawer({ open, onClose }: { open: boolean; onClose: () => void }) {
  const [items, setItems] = useState<Comparable[] | null>(null);

  useEffect(() => {
    if (!open) return;
    api.listComparables().then(setItems).catch(() => setItems([]));
  }, [open]);

  useEffect(() => {
    if (!open) return;
    function onKey(e: KeyboardEvent) { if (e.key === "Escape") onClose(); }
    window.addEventListener("keydown", onKey);
    return () => window.removeEventListener("keydown", onKey);
  }, [open, onClose]);

  if (!open) return null;
  return (
    <div className="fixed inset-0 z-40 flex justify-end bg-black/30" onClick={(e) => { if (e.target === e.currentTarget) onClose(); }}>
      <aside role="dialog" aria-labelledby="comps-drawer-title" className="h-full w-full max-w-md overflow-y-auto bg-white shadow-2xl">
        <div className="flex items-center justify-between border-b border-neutral-100 px-5 py-4">
          <h2 id="comps-drawer-title" className="text-base font-semibold">Comparables in evidence set</h2>
          <button onClick={onClose} aria-label="Close" className="rounded p-1 text-neutral-500 hover:bg-neutral-100 hover:text-neutral-800">
            <X size={18} />
          </button>
        </div>

        <div className="px-5 py-4">
          {items === null ? (
            <div className="text-sm text-neutral-500">Loading…</div>
          ) : items.length === 0 ? (
            <div className="text-sm text-neutral-500">No comparables in the workspace yet.</div>
          ) : (
            <ul className="space-y-2">
              {items.map((c) => {
                const psf = c.area_sqft && c.area_sqft > 0 ? c.rent_pa_gbp / c.area_sqft : null;
                return (
                  <li key={c.id} className="rounded-md border border-neutral-200 p-3">
                    <div className="font-medium text-sm text-neutral-900">{c.address}</div>
                    <div className="mt-1 text-xs text-neutral-600 tabular-nums">
                      £{c.rent_pa_gbp.toLocaleString()}/yr
                      {c.area_sqft && ` · ${c.area_sqft.toLocaleString()} sq ft`}
                      {psf != null && ` · £${psf.toFixed(0)}/sq ft`}
                    </div>
                    <div className="mt-1 text-xs text-neutral-500">
                      {c.use_class && <span>{c.use_class} · </span>}
                      {c.deal_date && <span>{format(parseISO(c.deal_date), "d MMM yyyy")} · </span>}
                      <span>{c.source}</span>
                    </div>
                    {c.notes && <div className="mt-1 text-xs text-neutral-500 italic">{c.notes}</div>}
                  </li>
                );
              })}
            </ul>
          )}
          <Link
            href="/comparables"
            onClick={onClose}
            className="mt-4 inline-flex items-center gap-1.5 text-sm text-blue-700 hover:underline"
          >
            Manage comparables <ExternalLink size={12} />
          </Link>
        </div>
      </aside>
    </div>
  );
}
